CREATE TABLE CIUDAD_ENTREGA (
    ID_CIUDAD NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL
);

CREATE TABLE CLIENTE (
    ID_CLIENTE NUMBER PRIMARY KEY,
    RUC VARCHAR2(13) NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    DIRECCION VARCHAR2(200)
);

CREATE TABLE COBRADOR (
    ID_COBRADOR NUMBER PRIMARY KEY,
    CEDULA VARCHAR2(10) NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    DIRECCION VARCHAR2(200)
);

CREATE TABLE COMPROBANTE (
    ID_COMPROBANTE NUMBER PRIMARY KEY,
    FECHA DATE NOT NULL,
    OBSERVACION VARCHAR2(300)
);

CREATE TABLE CUENTA_BANCARIA (
    ID_CUENTA_BANCO NUMBER PRIMARY KEY,
