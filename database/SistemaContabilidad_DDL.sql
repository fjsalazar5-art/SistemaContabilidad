);

CREATE TABLE MOV_BANCARIO_DET (
    ID_MOV_DET NUMBER PRIMARY KEY,
    ID_MOVIMIENTO NUMBER NOT NULL,
    FECHA DATE NOT NULL,
    ID_TIPO_TRANSACCION NUMBER NOT NULL,
    VALOR NUMBER(12,2) NOT NULL,
    CONSTRAINT FK_MOV_DET_MOV
        FOREIGN KEY (ID_MOVIMIENTO)
        REFERENCES MOV_BANCARIO(ID_MOVIMIENTO),
    CONSTRAINT FK_MOV_DET_TIPO
        FOREIGN KEY (ID_TIPO_TRANSACCION)
        REFERENCES TIPO_TRANSACCION(ID_TIPO_TRANSACCION)
);

CREATE TABLE PAGO_DETALLE (
    ID_PAGO_DETALLE NUMBER PRIMARY KEY,
    ID_PAGO NUMBER NOT NULL,
    FECHA_PAGO DATE NOT NULL,
    ID_FORMA_PAGO NUMBER NOT NULL,
    ID_COBRADOR NUMBER NOT NULL,
    VALOR NUMBER(12,2) NOT NULL,
    CONSTRAINT FK_PAGO_DET_PAGO
        FOREIGN KEY (ID_PAGO)
        REFERENCES PAGO(ID_PAGO),
    CONSTRAINT FK_PAGO_DET_FORMA
        FOREIGN KEY (ID_FORMA_PAGO)
        REFERENCES FORMA_PAGO(ID_FORMA_PAGO),
    CONSTRAINT FK_PAGO_DET_COBRADOR
        FOREIGN KEY (ID_COBRADOR)
        REFERENCES COBRADOR(ID_COBRADOR)
);

