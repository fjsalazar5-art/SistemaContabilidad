CREATE TABLE CUENTA_CONTABLE (
    ID_CUENTA NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL,
    ID_TIPO_CUENTA NUMBER NOT NULL,
    CONSTRAINT FK_CUENTA_TIPO
        FOREIGN KEY (ID_TIPO_CUENTA)
        REFERENCES TIPO_CUENTA(ID_TIPO_CUENTA)
);

CREATE TABLE FACTURA (
    ID_FACTURA NUMBER PRIMARY KEY,
    FECHA DATE NOT NULL,
    ID_CLIENTE NUMBER NOT NULL,
    ID_CIUDAD NUMBER NOT NULL,
    TOTAL NUMBER(12,2),
    CONSTRAINT FK_FACTURA_CLIENTE
        FOREIGN KEY (ID_CLIENTE)
        REFERENCES CLIENTE(ID_CLIENTE),
    CONSTRAINT FK_FACTURA_CIUDAD
        FOREIGN KEY (ID_CIUDAD)
        REFERENCES CIUDAD_ENTREGA(ID_CIUDAD)
);

CREATE TABLE COMPROBANTE_DETALLE (
    ID_COMP_DET NUMBER PRIMARY KEY,
    ID_COMPROBANTE NUMBER NOT NULL,
    ID_CUENTA NUMBER NOT NULL,
    DEBE NUMBER(12,2) DEFAULT 0,
    HABER NUMBER(12,2) DEFAULT 0,
    CONSTRAINT FK_COMP_DET_COMP
        FOREIGN KEY (ID_COMPROBANTE)
        REFERENCES COMPROBANTE(ID_COMPROBANTE),
    CONSTRAINT FK_COMP_DET_CUENTA
        FOREIGN KEY (ID_CUENTA)
        REFERENCES CUENTA_CONTABLE(ID_CUENTA)
);

CREATE TABLE FACTURA_DETALLE (
    ID_DETALLE NUMBER PRIMARY KEY,
    ID_FACTURA NUMBER NOT NULL,
    ARTICULO VARCHAR2(100) NOT NULL,
    CANTIDAD NUMBER NOT NULL,
    PRECIO NUMBER(12,2) NOT NULL,
    CONSTRAINT FK_DET_FACTURA
        FOREIGN KEY (ID_FACTURA)
        REFERENCES FACTURA(ID_FACTURA)
);

CREATE TABLE MOV_BANCARIO (
    ID_MOVIMIENTO NUMBER PRIMARY KEY,
