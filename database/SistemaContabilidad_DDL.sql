    DESCRIPCION VARCHAR2(200)
);

CREATE TABLE FORMA_PAGO (
    ID_FORMA_PAGO NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL
);

CREATE TABLE TIPO_CUENTA (
    ID_TIPO_CUENTA NUMBER PRIMARY KEY,
