    private void tblCiudadesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCiudadesMouseClicked
        // TODO add your handling code here:
        int fila = tblCiudades.getSelectedRow();

    idCiudadSeleccionada =
            Integer.parseInt(
                    tblCiudades.getValueAt(fila, 0)
                            .toString());

    txtNombreCiudad.setText(
            tblCiudades.getValueAt(fila, 1)
                    .toString());
    }//GEN-LAST:event_tblCiudadesMouseClicked

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        // TODO add your handling code here:
        if(idCiudadSeleccionada == 0){

        JOptionPane.showMessageDialog(
                this,
                "Seleccione una ciudad");

        return;
    }

    if(txtNombreCiudad.getText().trim().isEmpty()){

        JOptionPane.showMessageDialog(
                this,
                "Ingrese el nombre de la ciudad");

        txtNombreCiudad.requestFocus();

        return;
    }

    CiudadEntrega ciudad =
            new CiudadEntrega();

    ciudad.setIdCiudad(
            idCiudadSeleccionada);

    ciudad.setNombre(
            txtNombreCiudad.getText());

    CiudadEntregaDAO dao =
            new CiudadEntregaDAO();

    boolean modificado =
            dao.modificar(ciudad);

    if(modificado){

        JOptionPane.showMessageDialog(
                this,
                "Ciudad modificada correctamente");

        cargarCiudades();

        txtNombreCiudad.setText("");

        idCiudadSeleccionada = 0;

    }else{

        JOptionPane.showMessageDialog(
                this,
                "Error al modificar ciudad");
    }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        if(idCiudadSeleccionada == 0){

        JOptionPane.showMessageDialog(
                this,
                "Seleccione una ciudad");

        return;
    }

    int opcion =
            JOptionPane.showConfirmDialog(
                    this,
                    "¿Desea eliminar esta ciudad?",
                    "Confirmar eliminación",
                    JOptionPane.YES_NO_OPTION);

    if(opcion == JOptionPane.YES_OPTION){

        CiudadEntregaDAO dao =
                new CiudadEntregaDAO();

        boolean eliminado =
                dao.eliminar(idCiudadSeleccionada);

        if(eliminado){

            JOptionPane.showMessageDialog(
                    this,
                    "Ciudad eliminada correctamente");

            cargarCiudades();

            txtNombreCiudad.setText("");

            idCiudadSeleccionada = 0;

        }else{

            JOptionPane.showMessageDialog(
                    this,
                    "Error al eliminar ciudad");
        }
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
         DefaultTableModel modelo =
            (DefaultTableModel) tblCiudades.getModel();

    modelo.setRowCount(0);

    CiudadEntregaDAO dao =
            new CiudadEntregaDAO();

    ArrayList<CiudadEntrega> lista =
            dao.buscarPorNombre(
                    txtBuscarCiudad.getText());

    if(lista.isEmpty()){

        JOptionPane.showMessageDialog(
                this,
                "La ciudad no existe");

        txtBuscarCiudad.setText("");
        txtBuscarCiudad.requestFocus();

        return;
    }

    for(CiudadEntrega c : lista){

        modelo.addRow(new Object[]{
            c.getIdCiudad(),
            c.getNombre()
        });
    }

    txtBuscarCiudad.setText("");
    }//GEN-LAST:event_btnBuscarActionPerformed

