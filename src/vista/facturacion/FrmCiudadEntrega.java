    private void cargarCiudades(){

        DefaultTableModel modelo =
                (DefaultTableModel) tblCiudades.getModel();

        modelo.setRowCount(0);

        CiudadEntregaDAO dao =
                new CiudadEntregaDAO();

        ArrayList<CiudadEntrega> lista =
                dao.listar();

        for(CiudadEntrega c : lista){

            modelo.addRow(new Object[]{
                c.getIdCiudad(),
                c.getNombre()
            });
        }
    }
    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        if(txtNombreCiudad.getText().trim().isEmpty()){

        JOptionPane.showMessageDialog(
                this,
                "Ingrese el nombre de la ciudad");

        txtNombreCiudad.requestFocus();

        return;
    }

    CiudadEntrega ciudad =
            new CiudadEntrega();

    ciudad.setNombre(
            txtNombreCiudad.getText());

    CiudadEntregaDAO dao =
            new CiudadEntregaDAO();

    boolean guardado =
            dao.guardar(ciudad);

    if(guardado){

        JOptionPane.showMessageDialog(
                this,
                "Ciudad guardada correctamente");

        cargarCiudades();

        txtNombreCiudad.setText("");

    }else{

        JOptionPane.showMessageDialog(
                this,
                "Error al guardar ciudad");
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

