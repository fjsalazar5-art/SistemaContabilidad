    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        DefaultTableModel modelo =
            (DefaultTableModel) tblClientes.getModel();

    modelo.setRowCount(0);

    ClienteDAO dao = new ClienteDAO();

    ArrayList<Cliente> lista =
            dao.buscarPorNombre(
                    txtBuscarRuc.getText());

    if(lista.isEmpty()){

        JOptionPane.showMessageDialog(
                this,
                "El cliente no existe");

        txtBuscarRuc.setText("");
        txtBuscarRuc.requestFocus();

        return;
    }

    for(Cliente c : lista){

        modelo.addRow(new Object[]{
            c.getIdCliente(),
            c.getRuc(),
            c.getNombre(),
            c.getDireccion()
        });
    }

    txtBuscarRuc.setText("");
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void tblClientesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblClientesMouseClicked
        // TODO add your handling code here:
        
        int fila = tblClientes.getSelectedRow();

    idClienteSeleccionado =
            Integer.parseInt(
                    tblClientes.getValueAt(fila, 0)
                            .toString());

    txtRuc.setText(
            tblClientes.getValueAt(fila, 1)
                    .toString());

    txtNombre.setText(
            tblClientes.getValueAt(fila, 2)
                    .toString());

    txtDireccion.setText(
            tblClientes.getValueAt(fila, 3)
                    .toString());
    }//GEN-LAST:event_tblClientesMouseClicked

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        
        if(idClienteSeleccionado == 0){

        JOptionPane.showMessageDialog(
                this,
                "Seleccione un cliente de la tabla");

        return;
    }

    int opcion = JOptionPane.showConfirmDialog(
            this,
            "¿Desea eliminar este cliente?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION);

    if(opcion == JOptionPane.YES_OPTION){

        ClienteDAO dao = new ClienteDAO();

        boolean eliminado =
                dao.eliminar(idClienteSeleccionado);

        if(eliminado){

            JOptionPane.showMessageDialog(
                    this,
                    "Cliente eliminado correctamente");

            cargarClientes();

            txtRuc.setText("");
            txtNombre.setText("");
            txtDireccion.setText("");

            idClienteSeleccionado = 0;

        }else{

            JOptionPane.showMessageDialog(
                    this,
                    "Error al eliminar cliente");
        }
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

