    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
         if(idFacturaSeleccionada == 0){

        JOptionPane.showMessageDialog(
                this,
                "Seleccione una factura");

        return;
    }

    try{

        Cliente cliente =
                listaClientes.get(
                        cmbCliente.getSelectedIndex());

        CiudadEntrega ciudad =
                listaCiudades.get(
                        cmbCiudadEntrega.getSelectedIndex());

        Date fecha =
                new SimpleDateFormat("yyyy-MM-dd")
                .parse(txtFecha.getText());

        Factura factura =
                new Factura();

        factura.setIdFactura(
                idFacturaSeleccionada);

        factura.setFecha(
                fecha);

        factura.setIdCliente(
                cliente.getIdCliente());

        factura.setIdCiudad(
                ciudad.getIdCiudad());

        factura.setTotal(
                Double.parseDouble(
                        txtTotal.getText()));

        FacturaDAO facturaDAO =
                new FacturaDAO();

        boolean cabecera =
                facturaDAO.modificar(
                        factura);

        if(!cabecera){

            JOptionPane.showMessageDialog(
                    this,
                    "Error al actualizar factura");

            return;
        }

        FacturaDetalleDAO detalleDAO =
                new FacturaDetalleDAO();

        detalleDAO.eliminarPorFactura(
                idFacturaSeleccionada);

        for(int i = 0;
            i < tblDetalleFactura.getRowCount();
            i++){

            FacturaDetalle detalle =
                    new FacturaDetalle();

            detalle.setIdFactura(
                    idFacturaSeleccionada);

            detalle.setArticulo(
                    tblDetalleFactura
                    .getValueAt(i,0)
                    .toString());

            detalle.setCantidad(
                    Integer.parseInt(
                    tblDetalleFactura
                    .getValueAt(i,1)
                    .toString()));

            detalle.setPrecio(
                    Double.parseDouble(
                    tblDetalleFactura
                    .getValueAt(i,2)
                    .toString()));

            detalleDAO.guardar(
                    detalle);
        }
         cargarFacturas();
        JOptionPane.showMessageDialog(
                this,
                "Factura actualizada correctamente");
        

    }catch(Exception e){

        e.printStackTrace();

        JOptionPane.showMessageDialog(
                this,
                e.getMessage());
        
    }
    
    }//GEN-LAST:event_btnActualizarActionPerformed

