    private void cargarFacturas(){

    DefaultTableModel modelo =
            (DefaultTableModel)
            tblFacturas.getModel();

    modelo.setRowCount(0);

    FacturaDAO dao =
            new FacturaDAO();

    ArrayList<Factura> lista =
            dao.buscarPorCliente(
                    txtBuscarFactura.getText());

    for(Factura f : lista){

        String nombreCliente = "";

        for(Cliente c : listaClientes){

            if(c.getIdCliente() ==
                    f.getIdCliente()){

                nombreCliente =
                        c.getNombre();

                break;
            }
        }

        modelo.addRow(new Object[]{
            f.getIdFactura(),
            f.getFecha(),
            nombreCliente,
            f.getTotal()
        });
    }
}
    private void recalcularSubtotales(){

    for(int i = 0;
        i < tblDetalleFactura.getRowCount();
        i++){

        int cantidad =
                Integer.parseInt(
                tblDetalleFactura
                .getValueAt(i,1)
                .toString());

        double precio =
                Double.parseDouble(
                tblDetalleFactura
                .getValueAt(i,2)
                .toString());

        double subtotal =
                cantidad * precio;

        tblDetalleFactura.setValueAt(
                subtotal, i, 3);
    }

    calcularTotal();
}
    private void calcularTotal(){

    double total = 0;

    for(int i = 0;
        i < tblDetalleFactura.getRowCount();
        i++){

        total += Double.parseDouble(
                tblDetalleFactura
                .getValueAt(i,3)
                .toString());
    }

    txtTotal.setText(
            String.valueOf(total));
}
    private void cargarClientesCombo(){

    ClienteDAO dao =
            new ClienteDAO();

    listaClientes =
            dao.obtenerClientes();

    cmbCliente.removeAllItems();

    for(Cliente c : listaClientes){

        cmbCliente.addItem(
                c.getNombre());
    }
}
    private void cargarCiudadesCombo(){

    CiudadEntregaDAO dao =
            new CiudadEntregaDAO();

    listaCiudades =
            dao.listar();

    cmbCiudadEntrega.removeAllItems();

    for(CiudadEntrega c : listaCiudades){

        cmbCiudadEntrega.addItem(
                c.getNombre());
    }
}
