    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
      
    if(tblDetalleFactura.getRowCount() == 0){

        JOptionPane.showMessageDialog(
                this,
                "Debe ingresar al menos un detalle");

        return;
    }

    try{

        Cliente cliente =
                listaClientes.get(
                        cmbCliente.getSelectedIndex());

        CiudadEntrega ciudad =
                listaCiudades.get(
                        cmbCiudadEntrega.getSelectedIndex());

        Date fecha =
                new SimpleDateFormat("dd/MM/yyyy")
                .parse(txtFecha.getText());

        Factura factura =
                new Factura();

        factura.setFecha(fecha);

        factura.setIdCliente(
                cliente.getIdCliente());

        factura.setIdCiudad(
                ciudad.getIdCiudad());

        factura.setTotal(
                Double.parseDouble(
                        txtTotal.getText()));

        FacturaDAO facturaDAO =
                new FacturaDAO();

        int idFactura =
                facturaDAO.guardar(factura);

        System.out.println(
                "ID FACTURA: " + idFactura);

        FacturaDetalleDAO detalleDAO =
                new FacturaDetalleDAO();

        System.out.println(
                "FILAS DETALLE: "
                + tblDetalleFactura.getRowCount());

        for(int i = 0;
            i < tblDetalleFactura.getRowCount();
            i++){

            FacturaDetalle detalle =
                    new FacturaDetalle();

            detalle.setIdFactura(
                    idFactura);

            detalle.setArticulo(
                    tblDetalleFactura
                    .getValueAt(i,0)
                    .toString());

            detalle.setCantidad(
                    Integer.parseInt(
                    tblDetalleFactura
                    .getValueAt(i,1)
                    .toString()));

            detalle.setPrecio(
                    Double.parseDouble(
                    tblDetalleFactura
                    .getValueAt(i,2)
                    .toString()));

            detalle.setSubtotal(
                    Double.parseDouble(
                    tblDetalleFactura
                    .getValueAt(i,3)
                    .toString()));

            System.out.println(
                    detalle.getArticulo());

            boolean guardado =
                    detalleDAO.guardar(detalle);

            System.out.println(
                    "DETALLE GUARDADO: "
                    + guardado);
        }

        JOptionPane.showMessageDialog(
                this,
                "Factura guardada correctamente");

        txtArticulo.setText("");
        txtCantidad.setText("");
        txtPrecio.setText("");

        txtTotal.setText("0");

        DefaultTableModel modelo =
                (DefaultTableModel)
                tblDetalleFactura.getModel();

        modelo.setRowCount(0);

        cmbCliente.setSelectedIndex(0);
        cmbCiudadEntrega.setSelectedIndex(0);

    }catch(Exception e){

        e.printStackTrace();

        JOptionPane.showMessageDialog(
                this,
                e.getMessage());
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

