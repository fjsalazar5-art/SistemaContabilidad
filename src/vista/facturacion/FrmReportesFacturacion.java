    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        // TODO add your handling code here:
     
  
    if(txtFechaDesde.getText().trim().isEmpty()){

        JOptionPane.showMessageDialog(
                this,
                "Debe ingresar el año desde");

        txtFechaDesde.requestFocus();

        return;
    }

    if(txtFechaHasta.getText().trim().isEmpty()){

        JOptionPane.showMessageDialog(
                this,
                "Debe ingresar el año hasta");

        txtFechaHasta.requestFocus();

        return;
    }

    if(!rbVentasCiudad.isSelected()
            && !rbClienteArticulo.isSelected()){

        JOptionPane.showMessageDialog(
                this,
                "Debe seleccionar un tipo de reporte");

        return;
    }

    try{

        int anioDesde =
                Integer.parseInt(
                        txtFechaDesde.getText());

        int anioHasta =
                Integer.parseInt(
                        txtFechaHasta.getText());

        ReporteDAO dao =
                new ReporteDAO();

        DefaultTableModel modelo =
                new DefaultTableModel();

        ResultSet rs;

        if(rbVentasCiudad.isSelected()){

            modelo.addColumn("Ciudad");
            modelo.addColumn("Facturas");
            modelo.addColumn("Total");

            rs = dao.ventasPorCiudad(
                    anioDesde,
                    anioHasta);

            if(!rs.next()){

                JOptionPane.showMessageDialog(
                        this,
                        "No existen facturas entre los años "
                        + anioDesde +
                        " y " +
                        anioHasta);

                return;
            }

            do{

                modelo.addRow(new Object[]{
                    rs.getString("CIUDAD"),
                    rs.getInt("FACTURAS"),
                    rs.getDouble("TOTAL")
                });

            }while(rs.next());

            tblReporte.setModel(modelo);
        }

        if(rbClienteArticulo.isSelected()){

            ArrayList<String> clientes =
                    new ArrayList<>();

            modelo.addColumn("Articulo");

            ResultSet rsClientes =
                    dao.obtenerClientes();

            while(rsClientes.next()){

                String cliente =
                        rsClientes.getString(
                                "NOMBRE");

                clientes.add(cliente);

                modelo.addColumn(cliente);
            }

            ResultSet rsArticulos =
                    dao.obtenerArticulos(
                            anioDesde,
                            anioHasta);

            if(!rsArticulos.next()){

                JOptionPane.showMessageDialog(
                        this,
                        "No existen registros entre los años "
                        + anioDesde
                        + " y "
                        + anioHasta);

                return;
            }

            do{

                String articulo =
                        rsArticulos.getString(
                                "ARTICULO");

                Object[] fila =
                        new Object[
                                clientes.size() + 1];

                fila[0] = articulo;

                for(int i = 0;
                    i < clientes.size();
                    i++){

                    fila[i + 1] =
                            dao.obtenerTotalClienteArticulo(
                                    clientes.get(i),
                                    articulo,
                                    anioDesde,
                                    anioHasta);
                }

                modelo.addRow(fila);

            }while(rsArticulos.next());

            tblReporte.setModel(modelo);
        }

        txtFechaDesde.setText("");
        txtFechaHasta.setText("");

        txtFechaDesde.requestFocus();

        JOptionPane.showMessageDialog(
                this,
                "Reporte generado correctamente");

    }catch(NumberFormatException e){

        JOptionPane.showMessageDialog(
                this,
                "Los años deben ser numéricos");

    }catch(Exception e){

        JOptionPane.showMessageDialog(
                this,
                e.getMessage());
    }
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnImprimirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnImprimirActionPerformed
        // TODO add your handling code here:
       try{

        if(tblReporte.getRowCount() == 0){

            JOptionPane.showMessageDialog(
                    this,
                    "Primero debe generar el reporte");

            return;
        }

        String nombreArchivo = "";

        if(rbVentasCiudad.isSelected()){

            nombreArchivo =
                    "ReporteVentasCiudad.pdf";
        }

        if(rbClienteArticulo.isSelected()){

            nombreArchivo =
                    "ReporteClienteArticulo.pdf";
        }

        Document documento =
                new Document();

        PdfWriter.getInstance(
                documento,
                new FileOutputStream(
                        nombreArchivo));

        documento.open();

        documento.add(
                new Paragraph(
                        "SISTEMA DE FACTURACION"));

        documento.add(
                new Paragraph(
                        " "));

        if(rbVentasCiudad.isSelected()){

            documento.add(
                    new Paragraph(
                            "REPORTE DE VENTAS POR CIUDAD"));
        }

        if(rbClienteArticulo.isSelected()){

            documento.add(
                    new Paragraph(
                            "REPORTE CLIENTE - ARTICULO"));
        }

        documento.add(
                new Paragraph(
                        " "));

        PdfPTable tabla =
                new PdfPTable(
                        tblReporte.getColumnCount());

        for(int i = 0;
            i < tblReporte.getColumnCount();
            i++){

            tabla.addCell(
                    tblReporte.getColumnName(i));
        }

        for(int fila = 0;
            fila < tblReporte.getRowCount();
            fila++){

            for(int columna = 0;
                columna < tblReporte.getColumnCount();
                columna++){

                tabla.addCell(
                        tblReporte
                        .getValueAt(
                                fila,
                                columna)
                        .toString());
            }
        }

        documento.add(tabla);

        documento.close();

        JOptionPane.showMessageDialog(
                this,
                "PDF generado correctamente");

        Desktop.getDesktop().open(
                new File(nombreArchivo));

    }catch(Exception e){

        JOptionPane.showMessageDialog(
                this,
                e.getMessage());
    }
    }//GEN-LAST:event_btnImprimirActionPerformed

