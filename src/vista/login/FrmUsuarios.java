           private void cargarUsuarios(){

                    
                    DefaultTableModel modelo =
                            (DefaultTableModel) tblUsuarios.getModel();

                    modelo.setRowCount(0);

                    UsuarioDAO dao = new UsuarioDAO();

                    ArrayList<Usuario> lista =
                            dao.listar();

                    for(Usuario u : lista){

                        modelo.addRow(new Object[]{
                            u.getIdUsuario(),
                            u.getNombre(),
                            u.getNombreUsuario(),
                            u.getClave(),
                            u.getRol()
                        });
    }
                }
