    private void btBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btBuscarActionPerformed
        // TODO add your handling code here:
                      DefaultTableModel modelo =
            (DefaultTableModel) tblUsuarios.getModel();

    modelo.setRowCount(0);

    UsuarioDAO dao = new UsuarioDAO();

    ArrayList<Usuario> lista =
            dao.buscarPorUsuario(
                    txtBuscarUsuario.getText());

    if(lista.isEmpty()){

        JOptionPane.showMessageDialog(
                this,
                "El usuario no existe");

        txtBuscarUsuario.setText("");
        txtBuscarUsuario.requestFocus();

        return;
    }

    for(Usuario u : lista){

        modelo.addRow(new Object[]{
            u.getIdUsuario(),
            u.getNombre(),
            u.getNombreUsuario(),
            u.getClave(),
            u.getRol()
        });
    }

    txtBuscarUsuario.setText("");
    }//GEN-LAST:event_btBuscarActionPerformed

    private void tblUsuariosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblUsuariosMouseClicked
        // TODO add your handling code here:
    int fila = tblUsuarios.getSelectedRow();

    idUsuarioSeleccionado =
            Integer.parseInt(
                    tblUsuarios.getValueAt(fila,0)
                            .toString());

    txtNombre.setText(
            tblUsuarios.getValueAt(fila,1)
                    .toString());

    txtUsuario.setText(
            tblUsuarios.getValueAt(fila,2)
                    .toString());

    txtClave.setText(
            tblUsuarios.getValueAt(fila,3)
                    .toString());

    String rol =
            tblUsuarios.getValueAt(fila,4)
                    .toString();

    if(rol.equals("ADMIN")){

        rdbAdmin.setSelected(true);

    }else{

        rdbUsuario.setSelected(true);
    }
    }//GEN-LAST:event_tblUsuariosMouseClicked

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
         
           if(idUsuarioSeleccionado == 0){

        JOptionPane.showMessageDialog(
                this,
                "Seleccione un usuario de la tabla");

        return;
    }

    int opcion =
            JOptionPane.showConfirmDialog(
                    this,
                    "¿Desea eliminar este usuario?",
                    "Confirmar eliminación",
                    JOptionPane.YES_NO_OPTION);

    if(opcion == JOptionPane.YES_OPTION){

        UsuarioDAO dao = new UsuarioDAO();

        boolean eliminado =
                dao.eliminar(idUsuarioSeleccionado);

        if(eliminado){

            JOptionPane.showMessageDialog(
                    this,
                    "Usuario eliminado correctamente");

            cargarUsuarios();

            txtNombre.setText("");
            txtUsuario.setText("");
            txtClave.setText("");

            buttonGroupRol.clearSelection();

            idUsuarioSeleccionado = 0;

        }else{

            JOptionPane.showMessageDialog(
                    this,
                    "Error al eliminar usuario");
        }
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

